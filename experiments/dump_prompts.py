"""
experiments/dump_prompts.py — Dump all system prompts to LaTeX or Markdown.

Renders every prompt exported by `llmfca.prompting.prompts` into either:
  --format tex   : a single LaTeX file (default `appendix_prompts.tex`)
  --format md    : per-domain, per-strategy Markdown files (default `prompts/`)

The --output path is required (or the default is used). Use absolute paths
if you want to write into a directory outside the current working directory.

Usage:
    python -m experiments.dump_prompts
    python -m experiments.dump_prompts --format md
    python -m experiments.dump_prompts --format md --output /tmp/prompts/
    python -m experiments.dump_prompts --format tex --output /tmp/appendix_prompts.tex
"""
import os
import sys
import argparse
from datetime import datetime, timezone

CURRENT = os.path.dirname(os.path.abspath(__file__))
CODE_DIR = os.path.dirname(CURRENT)
REPO_ROOT = os.path.dirname(CODE_DIR)
sys.path.insert(0, CODE_DIR)

from llmfca.prompting.prompts import (
    INTEGER_PROMPT, INTEGER_PROMPT_FULL_CONTEXT, INTEGER_PROMPT_STEM_BASIS,
    GRAPHS_PROMPT, GRAPHS_PROMPT_FULL_CONTEXT, GRAPHS_PROMPT_STEM_BASIS,
    RCC_PROMPT, RCC_PROMPT_FULL_CONTEXT, RCC_PROMPT_STEM_BASIS,
    TOP_PROMPT, TOP_PROMPT_FULL_CONTEXT, TOP_PROMPT_STEM_BASIS,
    EVALUATION_RULES_FOL_IMPLICATION,
    PREDICATES_INTEGER_FOL, PREDICATES_GRAPHS_FOL,
    PREDICATES_RCC_FOL, PREDICATES_TOP_FOL,
)

DOMAIN_PREDICATES = {
    "INTEGER": PREDICATES_INTEGER_FOL,
    "GRAPHS": PREDICATES_GRAPHS_FOL,
    "RCC": PREDICATES_RCC_FOL,
    "TOP": PREDICATES_TOP_FOL,
}

PROMPT_LABELS = {
    "basic": "Baseline",
    "full_context": "CFC (with canonical context)",
    "stem_basis": "Stem basis",
}

DOMAIN_LABELS = {
    "INTEGER": "Integer Numbers",
    "GRAPHS": "Graph Theory",
    "RCC": "Region Connection Calculus",
    "TOP": "Top-Level Categories (KR Ontology)",
}

PROMPT_GROUPS = {
    "INTEGER": {
        "basic": INTEGER_PROMPT,
        "full_context": INTEGER_PROMPT_FULL_CONTEXT,
        "stem_basis": INTEGER_PROMPT_STEM_BASIS,
    },
    "GRAPHS": {
        "basic": GRAPHS_PROMPT,
        "full_context": GRAPHS_PROMPT_FULL_CONTEXT,
        "stem_basis": GRAPHS_PROMPT_STEM_BASIS,
    },
    "RCC": {
        "basic": RCC_PROMPT,
        "full_context": RCC_PROMPT_FULL_CONTEXT,
        "stem_basis": RCC_PROMPT_STEM_BASIS,
    },
    "TOP": {
        "basic": TOP_PROMPT,
        "full_context": TOP_PROMPT_FULL_CONTEXT,
        "stem_basis": TOP_PROMPT_STEM_BASIS,
    },
}

DOMAIN_FILE_KEYS = {
    "INTEGER": "integers",
    "GRAPHS": "graphs",
    "RCC": "rcc",
    "TOP": "top",
}

STRATEGY_FILE_KEYS = {
    "basic": "baseline",
    "stem_basis": "stem_basis",
    "full_context": "full_context",
}


def _escape_tex(s: str) -> str:
    """Escape LaTeX special characters except for backslash commands."""
    s = s.replace("%", r"\%")
    s = s.replace("{", r"\{")
    s = s.replace("}", r"\}")
    return s


def _resolve(arg: str) -> str:
    """Resolve `arg` against the appropriate base directory.

    - Absolute paths are returned as-is.
    - Paths starting with `experiments/` or `llmfca/` resolve against the
      `code/` directory.
    - Everything else resolves against the current working directory.
    """
    if os.path.isabs(arg):
        return arg
    if arg.startswith("experiments/") or arg.startswith("llmfca/"):
        return os.path.normpath(os.path.join(CODE_DIR, arg))
    return os.path.abspath(arg)


def build_tex_appendix() -> str:
    """Build the full LaTeX appendix as a single string."""
    out = []
    out.append(r"% Auto-generated by experiments.dump_prompts on " + datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"))
    out.append(r"% Do not edit by hand; rerun the script after any prompt change.")
    out.append(r"\section{System Prompts Used in the Attribute Exploration Runs}")
    out.append(r"\label{app:prompts}")
    out.append(r"This appendix lists, verbatim, every system prompt used during the Attribute Exploration experiments, organised by formal context and prompt strategy. Prompts are the same for every model; only the chat template, sampling temperature, and \texttt{logprobs} flag differ across runs.")
    out.append("")
    out.append(r"\subsection*{Shared evaluation rules}")
    out.append(r"\begin{verbatim}")
    out.append(_escape_tex(EVALUATION_RULES_FOL_IMPLICATION.strip()))
    out.append(r"\end{verbatim}")

    for domain_key, prompts in PROMPT_GROUPS.items():
        out.append("")
        out.append(r"\subsection*{" + DOMAIN_LABELS[domain_key] + r"}")
        for strategy, text in prompts.items():
            out.append(r"\subsubsection*{" + PROMPT_LABELS[strategy] + r"}")
            out.append(r"\begin{verbatim}")
            out.append(_escape_tex(text.strip()))
            out.append(r"\end{verbatim}")

    return "\n".join(out) + "\n"


def _attributes_list(predicates: dict[str, str]) -> str:
    """Render a dict of predicates as a markdown bullet list."""
    lines = ["### Attributes\n"]
    for key, desc in predicates.items():
        lines.append(f"- `{key}`: {desc}")
    lines.append("")
    return "\n".join(lines)


def build_markdown_files(output_dir: str) -> list[str]:
    """Write per-domain, per-strategy Markdown files to `output_dir`.
    Returns the list of written paths.
    """
    os.makedirs(output_dir, exist_ok=True)
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    written: list[str] = []

    def _write(path: str, title: str, text: str, predicates=None) -> None:
        with open(path, "w") as f:
            f.write(f"# {title}\n\n")
            f.write(f"Auto-generated by `experiments.dump_prompts` on {timestamp}.\n\n")
            if predicates:
                f.write(_attributes_list(predicates))
            f.write("````\n")
            f.write(text.strip())
            f.write("\n````\n")

    # --- Shared evaluation rules ---
    eval_path = os.path.join(output_dir, "evaluation_rules.md")
    _write(eval_path, "Shared Evaluation Rules", EVALUATION_RULES_FOL_IMPLICATION)
    written.append(eval_path)

    # --- Per-domain, per-strategy files ---
    for domain_key, prompts in PROMPT_GROUPS.items():
        domain_slug = DOMAIN_FILE_KEYS[domain_key]
        domain_label = DOMAIN_LABELS[domain_key]
        preds = DOMAIN_PREDICATES[domain_key]
        for strategy, text in prompts.items():
            strategy_slug = STRATEGY_FILE_KEYS[strategy]
            strategy_label = PROMPT_LABELS[strategy]
            filename = f"{domain_slug}_{strategy_slug}.md"
            filepath = os.path.join(output_dir, filename)
            _write(filepath, f"{domain_label} — {strategy_label}", text, preds)
            written.append(filepath)

    return written


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Dump all system prompts to LaTeX (.tex) or Markdown (.md)."
    )
    parser.add_argument(
        "--format", choices=["tex", "md"], default="md",
        help="Output format (default: md).",
    )
    parser.add_argument(
        "--output", default=None,
        help=(
            "Output path. For --format tex: .tex file path "
            "(default: appendix_prompts.tex in the current working directory). "
            "For --format md: output directory (default: prompts/)."
        ),
    )
    args = parser.parse_args()

    if args.format == "tex":
        output_path = _resolve(args.output or "appendix_prompts.tex")
        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        tex = build_tex_appendix()
        with open(output_path, "w") as f:
            f.write(tex)
        print(f"Saved: {output_path}")
        print(f"  Size: {len(tex)} chars, {tex.count(chr(10))} lines")
    else:
        output_dir = _resolve(args.output or "prompts")
        written = build_markdown_files(output_dir)
        print(f"Saved {len(written)} files to {output_dir}/")
        for path in written:
            rel = os.path.relpath(path, output_dir)
            size = os.path.getsize(path)
            print(f"  {rel}  ({size} bytes)")


if __name__ == "__main__":
    main()
